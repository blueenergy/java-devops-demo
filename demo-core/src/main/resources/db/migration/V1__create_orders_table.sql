-- 订单表。
--
-- 注意表名是复数 orders：ORDER 是 SQL 保留字，直接用 order 会报语法错误。
CREATE TABLE orders
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol     VARCHAR(32)    NOT NULL,
    quantity   NUMERIC(19, 4) NOT NULL,
    unit_price NUMERIC(19, 4) NOT NULL,
    status     VARCHAR(16)    NOT NULL,
    created_at TIMESTAMPTZ    NOT NULL,
    updated_at TIMESTAMPTZ    NOT NULL,
    version    BIGINT         NOT NULL DEFAULT 0,

    CONSTRAINT ck_orders_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_orders_unit_price_positive CHECK (unit_price > 0),
    CONSTRAINT ck_orders_status_valid CHECK (status IN ('NEW', 'FILLED', 'CANCELLED'))
);

-- 按标的 + 时间倒序查询是主要读路径
CREATE INDEX idx_orders_symbol_created_at ON orders (symbol, created_at DESC);

-- 状态 + 创建时间，用于运维排查「卡在 NEW 的单」
CREATE INDEX idx_orders_status_created_at ON orders (status, created_at DESC);

COMMENT ON TABLE orders IS '订单表';
COMMENT ON COLUMN orders.version IS '乐观锁版本号，由 JPA @Version 维护';
